import { createProviderRuntimeGeneratorContract, validateProviderRuntimeGeneratorContract, isProviderRuntimeGeneratorAdmissionAllowed } from "./provider-runtime-generator-contract.js";
import { validateProviderRuntimeIR } from "./provider-runtime-ir.js";

const swiftString = value => JSON.stringify(String(value));
const swiftOptionalInt = value => value === null ? "nil" : String(value);

function renderStage(stage) {
  const deps = stage.dependsOn.length ? `[${stage.dependsOn.map(swiftString).join(", ")}]` : "[]";
  return `        GeneratedStage(id: ${swiftString(stage.id)}, order: ${stage.order}, dependsOn: ${deps}, mutation: ${swiftString(stage.mutation)}, resultOnSuccess: ${swiftString(stage.resultOnSuccess)}, timeoutMs: ${swiftOptionalInt(stage.timeoutMs)}, onParseError: ${swiftString(stage.failure.onParseError)}, onTimeout: ${swiftString(stage.failure.onTimeout)}, onUpstreamError: ${swiftString(stage.failure.onUpstreamError)})`;
}

function renderSwift(ir, contract) {
  const stages = ir.stages.map(renderStage).join(",\n");
  const transports = ir.transports.transports.map(swiftString).join(", ");
  const sourceChainId = swiftString(ir.provenance?.sourceChainId || "");
  return `// Generated by Provider Runtime Generator Contract v1.
// Source provenance: ${ir.provenance?.sourceChainId || "none"}
// This source is generated only from an admitted Provider Runtime IR.

import Foundation
import NetworkExtension

public struct GeneratedStage: Sendable {
    public let id: String
    public let order: Int
    public let dependsOn: [String]
    public let mutation: String
    public let resultOnSuccess: String
    public let timeoutMs: Int?
    public let onParseError: String
    public let onTimeout: String
    public let onUpstreamError: String
}

public enum GeneratedProviderRuntime {
    public static let sourceChainId = ${sourceChainId}
    public static let transports: [String] = [${transports}]
    public static let stages: [GeneratedStage] = [
${stages}
    ]
    public static let maxBufferedBytes: Int? = ${swiftOptionalInt(ir.resources?.maxBufferedBytes ?? null)}
    public static let perFlowBufferedBytes: Int? = ${swiftOptionalInt(ir.resources?.perFlowBufferedBytes ?? null)}
    public static let maxConcurrentFlows: Int? = ${swiftOptionalInt(ir.resources?.maxConcurrentFlows ?? null)}

    public static func validateStageOrder() -> Bool {
        var seen = Set<String>()
        for stage in stages {
            for dependency in stage.dependsOn where !seen.contains(dependency) { return false }
            seen.insert(stage.id)
        }
        return true
    }
}

public final class ${contract.artifact.entrypoint}: NEDNSProxyProvider {
    public override func startProxy(options: [String : Any]? = nil, completionHandler: @escaping (Error?) -> Void) {
        completionHandler(GeneratedProviderRuntime.validateStageOrder() ? nil : NSError(domain: "ConfigurationPlatform.ProviderRuntime", code: 1))
    }

    public override func stopProxy(withReason reason: NEProviderStopReason, completionHandler: @escaping () -> Void) {
        completionHandler()
    }
}
`;
}

export function generateProviderRuntimeSwift(input = {}) {
  const contract = input.contract || createProviderRuntimeGeneratorContract(input);
  const runtimeIR = input.runtimeIR;
  const admission = isProviderRuntimeGeneratorAdmissionAllowed({ contract, runtimeIR });
  if (!admission.allowed) {
    return Object.freeze({ status: "BLOCKED", artifact: null, admission });
  }
  const source = renderSwift(runtimeIR, contract);
  const artifact = Object.freeze({
    language: contract.output.language,
    runtimeTarget: contract.output.runtimeTarget,
    entrypoint: contract.artifact.entrypoint,
    sourceChainId: runtimeIR.provenance?.sourceChainId || null,
    files: Object.freeze([{ path: `${contract.artifact.entrypoint}.swift`, content: source }]),
  });
  return Object.freeze({ status: "GENERATED", artifact, admission });
}

export function validateGeneratedProviderRuntimeSwift(result = {}) {
  const errors = [];
  if (result?.status !== "GENERATED") errors.push("PROVIDER_RUNTIME_SWIFT_GENERATION_REQUIRED");
  const file = result?.artifact?.files?.[0];
  if (!file || !file.path.endsWith(".swift") || typeof file.content !== "string" || file.content.length === 0) errors.push("PROVIDER_RUNTIME_SWIFT_SOURCE_REQUIRED");
  if (result?.artifact?.language !== "SWIFT") errors.push("PROVIDER_RUNTIME_SWIFT_LANGUAGE_REQUIRED");
  if (result?.artifact?.runtimeTarget !== "NETWORK_EXTENSION") errors.push("PROVIDER_RUNTIME_SWIFT_TARGET_REQUIRED");
  if (!result?.admission?.allowed) errors.push("PROVIDER_RUNTIME_SWIFT_ADMISSION_REQUIRED");
  return Object.freeze({ valid: errors.length === 0, errors: Object.freeze(errors) });
}

export { validateProviderRuntimeIR };